#!/usr/bin/env python3
"""Generate the dev bridge's command dispatcher from src-tauri/src/lib.rs.

The dev bridge (src-tauri/src/dev_bridge/) lets a plain browser tab drive the
running Studio's Rust core, so the webview can be developed and reviewed against
a live kernel outside the native window. It needs one match arm per Tauri
command; this script writes them so the list never drifts by hand.

Run after adding, removing or changing a #[tauri::command] in lib.rs:

    python3 scripts/gen-dev-bridge.py

A unit test in dev_bridge fails when the generated file is stale.
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = ROOT / "src-tauri" / "src" / "lib.rs"
OUT = ROOT / "src-tauri" / "src" / "dev_bridge" / "dispatch.rs"

COMMAND = re.compile(
    r'#\[tauri::command\(rename_all = "snake_case"\)\]\s*'
    r"(?:#\[[^\]]*\]\s*)*"
    r"(?:pub\s+)?async fn (\w+)\s*\((.*?)\)\s*->",
    re.S,
)
STATE = re.compile(r"State<'_,\s*(.+)>$")


def split_params(raw: str) -> list[tuple[str, str]]:
    params, depth, cur = [], 0, ""
    for ch in raw:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            params.append(cur)
            cur = ""
        else:
            cur += ch
    params.append(cur)
    out = []
    for p in params:
        p = " ".join(p.split())
        if not p:
            continue
        name, ty = p.split(":", 1)
        out.append((name.strip(), ty.strip()))
    return out


def arm(name: str, params: list[tuple[str, str]]) -> str:
    fields, call = [], []
    for pname, ty in params:
        state = STATE.match(ty)
        if ty in ("AppHandle", "tauri::AppHandle"):
            call.append("app.clone()")
        elif state:
            call.append(f"app.state::<{state.group(1)}>()")
        else:
            fields.append(f"            {pname}: {ty},")
            call.append(f"a.{pname}")
    lines = [f'        "{name}" => {{']
    if fields:
        lines.append("            #[derive(serde::Deserialize)]")
        lines.append("            struct A {")
        lines.extend("    " + f for f in fields)
        lines.append("            }")
        lines.append("            let a: A = parse(args)?;")
    lines.append(f"            reply(super::super::{name}({', '.join(call)}).await)")
    lines.append("        }")
    return "\n".join(lines)


def main() -> None:
    src = LIB.read_text()
    commands = [(m.group(1), split_params(m.group(2))) for m in COMMAND.finditer(src)]
    declared = len(re.findall(r"#\[tauri::command", src))
    if len(commands) != declared:
        raise SystemExit(
            f"parsed {len(commands)} of {declared} commands; extend the pattern in {__file__}"
        )
    arms = "\n".join(arm(n, p) for n, p in commands)
    names = "\n".join(f'    "{n}",' for n, _ in commands)
    OUT.write_text(
        f"""// @generated by scripts/gen-dev-bridge.py from src/lib.rs. Do not edit by hand.

#![allow(clippy::all, unused_imports)]

use super::super::*;
use tauri::{{AppHandle, Manager}};

/// Every command the dev bridge can relay, in lib.rs order.
#[allow(dead_code)]
pub const COMMANDS: &[&str] = &[
{names}
];

fn parse<T: serde::de::DeserializeOwned>(args: serde_json::Value) -> Result<T, String> {{
    serde_json::from_value(args).map_err(|e| format!("invalid arguments: {{e}}"))
}}

fn reply<T: serde::Serialize>(r: Result<T, String>) -> Result<serde_json::Value, String> {{
    r.and_then(|v| serde_json::to_value(v).map_err(|e| e.to_string()))
}}

pub async fn dispatch(
    app: AppHandle,
    cmd: &str,
    args: serde_json::Value,
) -> Result<serde_json::Value, String> {{
    match cmd {{
{arms}
        other => Err(format!("unknown command: {{other}}")),
    }}
}}
"""
    )
    print(f"wrote {len(commands)} commands to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
